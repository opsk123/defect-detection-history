import assert from 'node:assert/strict';
import {filteredRows,csvCell,classCounts,sessionRows} from '../docs/dashboard-utils.mjs';
const rows=[{mode:'inference',line:'A',status:'review_required',boxes:[{class_key:'sawing'},{class_key:'sawing'}]},{mode:'fixture',line:'A',boxes:[{class_key:'sawing'}]},{mode:'inference',line:'B',boxes:[]}];
assert.equal(filteredRows(rows).length,2);
assert.equal(filteredRows(rows,{line:'A'}).length,1);
assert.equal(filteredRows(rows,{fixture:true}).length,3);
assert.equal(classCounts(filteredRows(rows)).sawing,1);
assert.equal(csvCell('=SUM(A1)'), '"\'=SUM(A1)"');
assert.equal(csvCell('a"b'), '"a""b"');
console.log('PASS: filters, fixture separation, per-observation counts, CSV escaping');
const sample=(run,status,id)=>({run,status,id,time:'2026-11-10T00:00:00Z',line:'A',mode:'inference',class:'normal',boxes:[]});
const photos=[...Array.from({length:33},(_,i)=>sample('run1','normal_candidate','n'+i)),sample('run2','normal_candidate','m1'),sample('run2','review_required','m2'),sample('run3','not_run','u1'),sample('run3','normal_candidate','u2')];
const sessions=sessionRows(photos);
assert.equal(sessions.length,3);
assert.equal(sessions.filter(r=>r.status==='normal_candidate').length,1);
assert.equal(sessions.reduce((sum,r)=>sum+r.frame_count,0),37);
assert.equal(sessionRows(photos,{status:'normal_candidate'}).length,1);
assert.equal(sessions.find(r=>r.run==='run2').status,'review_required');
assert.equal(sessions.find(r=>r.run==='run3').status,'not_run');
console.log('PASS: 37 photos become 3 session records, only 1 normal session; filters preserve mismatches');
